/**
 * Asynchronous, cached replacement for {@link ChunkGenerator#findNearestMapStructure} used by the Dwarven Compass.
 * <p>
 * Vanilla's locate runs entirely on the server thread and, for every placement cell whose structure-start state is
 * unknown, calls {@code level.getChunk(x, z, STRUCTURE_STARTS)} - i.e. it <b>generates chunks synchronously</b>.
 * A single compass query stalled the server for hundreds of milliseconds (140-600 ms measured on a fresh world, more
 * with slow storage), and the old compass repeated that query every tick while no structure was found.
 * <p>
 * This locator splits the work:
 * <ol>
 *     <li><b>Worker thread</b> (pure math + noise sampling, no chunk loading): walks the placement grid ring by ring in
 *     vanilla order and evaluates every cell exactly like world generation would - placement/frequency/exclusion-zone
 *     check ({@code isStructureChunk}), then {@link Structure#findGenerationPoint} (thread safe, it is what the worldgen
 *     worker threads run) and the biome check vanilla performs in {@code Structure.generate}. Every verdict is
 *     cached per (seed, dimension, structure), so repeated searches are almost free.</li>
 *     <li><b>IO thread</b>: the surviving candidates are confirmed nearest first by reading only the saved
 *     {@code structures.starts} of the candidate chunk (the same data vanilla's structure check reads, but without
 *     blocking the server thread). A chunk that was never saved is generated by exactly the code the worker just
 *     evaluated, so the prediction is authoritative for it. Nothing is ever loaded or generated.</li>
 *     <li><b>Server thread</b>: only bookkeeping (well below a millisecond per search). Results are handed out
 *     through tickets polled by the caller.</li>
 * </ol>
 * The search returns the truly nearest (2D, squared-distance comparison) candidate instead of vanilla's
 * "first hit in scan order", and it keeps scanning only while a ring could still contain something closer.
 */
@Mod.EventBusSubscriber(modid = DivineRelics.MODID, bus = Mod.EventBusSubscriber.Bus.FORGE)
public final class StructureLocator {
    private static final Logger LOGGER = LogUtils.getLogger();

    public static final int DEFAULT_SEARCH_RADIUS = 100;

    private static final byte UNKNOWN = 0;
    private static final byte REJECTED = 1;
    private static final byte CANDIDATE = 2;
    /** Upper bound for a single cell cache (a full 100-ring search touches ~40k cells). */
    private static final int MAX_CACHED_CELLS = 1 << 18;
    /** Finished tickets that were never polled are dropped after this delay. */
    private static final long TICKET_EXPIRY_MILLIS = TimeUnit.MINUTES.toMillis(10);

    private static final ThreadPoolExecutor WORKER = createWorker();
    private static final Map<CacheKey, Long2ByteOpenHashMap> CELL_CACHE = new ConcurrentHashMap<>();
    /** Bumped whenever the server stops so that in-flight searches of the previous world are discarded. */
    private static final AtomicInteger GENERATION = new AtomicInteger();
    /** Server-thread only. */
    private static final Long2ObjectMap<Ticket> TICKETS = new Long2ObjectOpenHashMap<>();

    private StructureLocator() {
    }

    public enum Status {PENDING, FOUND, NOT_FOUND, UNKNOWN}

    public record Result(Status status, @Nullable BlockPos pos, @Nullable ResourceKey<Level> dimension) {
        private static final Result PENDING = new Result(Status.PENDING, null, null);
        private static final Result UNKNOWN = new Result(Status.UNKNOWN, null, null);
    }

    private record CacheKey(long seed, ResourceKey<Level> dimension, ResourceLocation structure) {
    }

    private record Candidate(ChunkPos chunk, BlockPos locatePos, long distanceSqr) {
    }

    private static final class Ticket {
        final ResourceKey<Level> dimension;
        final CompletableFuture<Optional<BlockPos>> future;
        long completedAtMillis;

        Ticket(ResourceKey<Level> dimension, CompletableFuture<Optional<BlockPos>> future) {
            this.dimension = dimension;
            this.future = future;
        }
    }

    /**
     * Starts an asynchronous search and returns a ticket that can be {@link #poll(long) polled} from the server
     * thread. Tickets are random, so a ticket persisted in item NBT across a restart simply reports
     * {@link Status#UNKNOWN} instead of picking up an unrelated result.
     */
    public static long submit(ServerLevel level, @Nullable ResourceLocation structureId, BlockPos origin, int radius) {
        purgeExpiredTickets();
        long id;
        do {
            id = ThreadLocalRandom.current().nextLong();
        } while (id == 0L || TICKETS.containsKey(id));

        Ticket ticket = new Ticket(level.dimension(), locate(level, structureId, origin, radius));
        ticket.future.whenComplete((pos, error) -> ticket.completedAtMillis = System.currentTimeMillis());
        TICKETS.put(id, ticket);
        return id;
    }

    /**
     * Server thread only. Returns the state of a ticket; finished tickets are consumed by this call.
     */
    public static Result poll(long ticketId) {
        Ticket ticket = TICKETS.get(ticketId);
        if (ticket == null) {
            return Result.UNKNOWN;
        }
        if (!ticket.future.isDone()) {
            return Result.PENDING;
        }
        TICKETS.remove(ticketId);
        Optional<BlockPos> pos = ticket.future.isCompletedExceptionally() ? Optional.empty() : ticket.future.getNow(Optional.empty());
        return pos.map(p -> new Result(Status.FOUND, p, ticket.dimension))
                .orElseGet(() -> new Result(Status.NOT_FOUND, null, ticket.dimension));
    }

    /**
     * Must be called on the server thread. The returned future is always completed on the server thread.
     */
    public static CompletableFuture<Optional<BlockPos>> locate(ServerLevel level, @Nullable ResourceLocation structureId, BlockPos origin, int radius) {
        if (structureId == null || !level.getServer().getWorldData().worldGenSettings().generateStructures()) {
            // Without structure generation every prediction would be a phantom target.
            return CompletableFuture.completedFuture(Optional.empty());
        }
        Registry<Structure> registry = level.registryAccess().registryOrThrow(Registry.STRUCTURE_REGISTRY);
        Optional<Holder<Structure>> holder = registry.getHolder(ResourceKey.create(Registry.STRUCTURE_REGISTRY, structureId));
        if (holder.isEmpty()) {
            // Structure removed by a datapack: fail gracefully instead of getHolderOrThrow crashing the server.
            LOGGER.debug("Structure {} is not registered, the search is skipped", structureId);
            return CompletableFuture.completedFuture(Optional.empty());
        }

        ChunkGenerator generator = level.getChunkSource().getGenerator();
        Structure structure = holder.get().value();
        Set<Holder<Biome>> possibleBiomes = generator.getBiomeSource().possibleBiomes();
        if (structure.biomes().stream().noneMatch(possibleBiomes::contains)) {
            // e.g. the Nether or the End: the structure can never generate here, so there is nothing to scan.
            return CompletableFuture.completedFuture(Optional.empty());
        }

        List<RandomSpreadStructurePlacement> placements = new ArrayList<>(1);
        boolean unsupportedPlacement = false;
        for (Holder<StructureSet> setHolder : (Iterable<Holder<StructureSet>>) generator.possibleStructureSets()::iterator) {
            StructureSet set = setHolder.value();
            boolean containsStructure = false;
            for (StructureSet.StructureSelectionEntry entry : set.structures()) {
                if (entry.structure().value() == structure) {
                    containsStructure = true;
                    break;
                }
            }
            if (!containsStructure) {
                continue;
            }
            if (set.placement() instanceof RandomSpreadStructurePlacement randomSpread && set.structures().size() == 1) {
                placements.add(randomSpread);
            } else {
                unsupportedPlacement = true;
            }
        }

        if (unsupportedPlacement) {
            // A datapack moved the structure into a weighted or concentric-ring set. Those need the full vanilla
            // logic, so keep behaving exactly like the compass always did rather than guessing.
            LOGGER.debug("Structure {} uses an unsupported placement, falling back to the vanilla locate", structureId);
            Pair<BlockPos, Holder<Structure>> result = generator.findNearestMapStructure(level, HolderSet.direct(holder.get()), origin, radius, false);
            return CompletableFuture.completedFuture(Optional.ofNullable(result).map(Pair::getFirst));
        }
        if (placements.isEmpty()) {
            return CompletableFuture.completedFuture(Optional.empty());
        }

        CacheKey cacheKey = new CacheKey(level.getSeed(), level.dimension(), structureId);
        Search search = new Search(level, structureId, structure, placements, origin, radius,
                CELL_CACHE.computeIfAbsent(cacheKey, key -> new Long2ByteOpenHashMap()));
        scheduleScan(search);
        return search.result;
    }

    private static void scheduleScan(Search search) {
        CompletableFuture.runAsync(() -> scan(search), WORKER)
                .whenComplete((ignored, error) -> search.server.execute(() -> onScanned(search, error)));
    }

    /**
     * Worker thread: walks placement rings and adds cells that would really generate the structure to
     * {@link Search#pending}. Stops as soon as the next ring cannot contain anything closer than the best pending
     * candidate. The pending list is handed back and forth between the worker and the server thread, never shared
     * concurrently (the executor / future chain provides the happens-before edges).
     */
    private static void scan(Search search) {
        long start = System.nanoTime();
        List<Candidate> pending = search.pending;
        long bestDistanceSqr = pending.isEmpty() ? Long.MAX_VALUE : pending.get(0).distanceSqr();
        int originChunkX = SectionPos.blockToSectionCoord(search.origin.getX());
        int originChunkZ = SectionPos.blockToSectionCoord(search.origin.getZ());

        for (int p = 0; p < search.placements.size(); p++) {
            RandomSpreadStructurePlacement placement = search.placements.get(p);
            int spacing = placement.spacing();
            int ring = search.nextRing[p];

            for (; ring <= search.radius; ring++) {
                if (GENERATION.get() != search.generation) {
                    throw new CancellationException("Server stopped");
                }
                if (bestDistanceSqr != Long.MAX_VALUE && ringLowerBoundSqr(ring, spacing) > bestDistanceSqr) {
                    break;
                }
                for (int dx = -ring; dx <= ring; dx++) {
                    boolean edgeColumn = dx == -ring || dx == ring;
                    int step = edgeColumn ? 1 : Math.max(1, 2 * ring);
                    for (int dz = -ring; dz <= ring; dz += step) {
                        ChunkPos chunk = placement.getPotentialStructureChunk(search.seed,
                                originChunkX + spacing * dx, originChunkZ + spacing * dz);
                        if (cellState(search, placement, chunk) != CANDIDATE) {
                            continue;
                        }
                        BlockPos locatePos = placement.getLocatePos(chunk);
                        long offX = locatePos.getX() - search.origin.getX();
                        long offZ = locatePos.getZ() - search.origin.getZ();
                        long distanceSqr = offX * offX + offZ * offZ;
                        pending.add(new Candidate(chunk, locatePos, distanceSqr));
                        bestDistanceSqr = Math.min(bestDistanceSqr, distanceSqr);
                    }
                }
            }
            search.nextRing[p] = ring;
        }
        pending.sort(Comparator.comparingLong(Candidate::distanceSqr));
        search.workerNanos += System.nanoTime() - start;
    }

    /**
     * Squared lower bound of the horizontal distance between the origin and any cell of ring {@code ring}: one axis is
     * offset by {@code ring} regions, which puts the structure chunk at least {@code (ring - 1) * spacing} whole
     * chunks away from the origin's chunk.
     */
    private static long ringLowerBoundSqr(int ring, int spacing) {
        long lowerBound = Math.max(0L, (long) (ring - 1) * spacing * 16L);
        return lowerBound * lowerBound;
    }

    /** Smallest distance (squared) at which a not yet scanned ring could still hold a candidate. */
    private static long unscannedLowerBoundSqr(Search search) {
        long bound = Long.MAX_VALUE;
        for (int p = 0; p < search.placements.size(); p++) {
            if (search.nextRing[p] <= search.radius) {
                bound = Math.min(bound, ringLowerBoundSqr(search.nextRing[p], search.placements.get(p).spacing()));
            }
        }
        return bound;
    }

    private static byte cellState(Search search, RandomSpreadStructurePlacement placement, ChunkPos chunk) {
        long key = chunk.toLong();
        byte state;
        synchronized (search.cache) {
            state = search.cache.get(key);
        }
        if (state != UNKNOWN) {
            return state;
        }
        search.evaluatedCells++;
        state = canGenerateAt(search, placement, chunk) ? CANDIDATE : REJECTED;
        synchronized (search.cache) {
            if (search.cache.size() >= MAX_CACHED_CELLS) {
                search.cache.clear();
            }
            search.cache.put(key, state);
        }
        return state;
    }

    /**
     * Mirrors {@code ChunkGenerator.createStructures} for a single-structure random-spread set: placement
     * (spread + frequency + exclusion zone), generation point and biome validation. Pure function of the seed.
     */
    private static boolean canGenerateAt(Search search, RandomSpreadStructurePlacement placement, ChunkPos chunk) {
        if (!placement.isStructureChunk(search.generator, search.randomState, search.seed, chunk.x, chunk.z)) {
            return false;
        }
        Structure structure = search.structure;
        Structure.GenerationContext context = new Structure.GenerationContext(search.registryAccess, search.generator,
                search.generator.getBiomeSource(), search.randomState, search.templateManager, search.seed, chunk,
                search.heightAccessor, structure.biomes()::contains);
        Optional<Structure.GenerationStub> stub = structure.findGenerationPoint(context);
        if (stub.isEmpty()) {
            return false;
        }
        BlockPos pos = stub.get().position();
        Holder<Biome> biome = search.generator.getBiomeSource().getNoiseBiome(QuartPos.fromBlock(pos.getX()),
                QuartPos.fromBlock(pos.getY()), QuartPos.fromBlock(pos.getZ()), search.randomState.sampler());
        return structure.biomes().contains(biome);
    }

    /**
     * Server thread: the worker finished a scan pass.
     */
    private static void onScanned(Search search, @Nullable Throwable error) {
        if (GENERATION.get() != search.generation) {
            search.result.complete(Optional.empty());
            return;
        }
        if (error != null) {
            if (!(error instanceof CancellationException) && !(error.getCause() instanceof CancellationException)) {
                LOGGER.error("Structure search for {} failed", search.structureId, error);
            }
            search.result.complete(Optional.empty());
            return;
        }
        confirmNext(search);
    }

    /**
     * Server thread: confirms the nearest pending candidate against the saved chunk data, or scans further.
     */
    private static void confirmNext(Search search) {
        List<Candidate> pending = search.pending;
        long unscannedBound = unscannedLowerBoundSqr(search);
        if (pending.isEmpty() || pending.get(0).distanceSqr() > unscannedBound) {
            // Nothing left to confirm, or a closer candidate was rejected and the rings the worker skipped because
            // of it may still hold something nearer than the next candidate.
            if (unscannedBound != Long.MAX_VALUE) {
                scheduleScan(search);
            } else {
                complete(search, Optional.empty());
            }
            return;
        }
        Candidate candidate = pending.get(0);
        CollectFields savedData = new CollectFields(new FieldSelector(IntTag.TYPE, "DataVersion"),
                new FieldSelector("structures", CompoundTag.TYPE, "starts"));
        search.level.getChunkSource().chunkMap.chunkScanner().scanChunk(candidate.chunk(), savedData)
                .whenComplete((ignored, error) -> search.server.execute(() -> onCandidateRead(search, candidate, savedData, error)));
    }

    /**
     * Server thread: the saved data of a candidate chunk was read on the IO thread.
     */
    private static void onCandidateRead(Search search, Candidate candidate, CollectFields savedData, @Nullable Throwable readError) {
        if (GENERATION.get() != search.generation) {
            search.result.complete(Optional.empty());
            return;
        }
        if (isStartPresent(search, candidate, savedData.getResult(), readError)) {
            complete(search, Optional.of(candidate.locatePos()));
            return;
        }
        // The saved chunk disagrees with the prediction (e.g. it was generated by an older version of the mod).
        synchronized (search.cache) {
            search.cache.put(candidate.chunk().toLong(), REJECTED);
        }
        search.pending.remove(candidate);
        confirmNext(search);
    }

    /**
     * Mirrors {@code StructureCheck.tryLoadFromStorage}: a saved chunk is authoritative. Chunks that were never saved
     * are generated by the exact code the worker evaluated, so the prediction is trusted for them.
     */
    private static boolean isStartPresent(Search search, Candidate candidate, @Nullable Tag saved, @Nullable Throwable readError) {
        if (readError == null && !(saved instanceof CompoundTag)) {
            return true;
        }
        if (readError != null || !(saved instanceof CompoundTag root) || !root.contains("structures", Tag.TAG_COMPOUND)
                || ChunkStorage.getVersion(root) != SharedConstants.getCurrentVersion().getDataVersion().getVersion()) {
            // Unreadable, or written by another game version and in need of datafixing: let vanilla decide. This
            // blocks the server thread briefly, but only happens for chunks from older worlds.
            return search.level.structureManager().checkStructurePresence(candidate.chunk(), search.structure, false)
                    != StructureCheckResult.START_NOT_PRESENT;
        }
        CompoundTag start = root.getCompound("structures").getCompound("starts").getCompound(search.structureId.toString());
        return !start.isEmpty() && !"INVALID".equals(start.getString("id"));
    }

    private static void complete(Search search, Optional<BlockPos> result) {
        LOGGER.debug("Located {} from {} -> {} ({} cells evaluated, {} ms of worker time)", search.structureId,
                search.origin.toShortString(), result.map(BlockPos::toShortString).orElse("nothing"),
                search.evaluatedCells, TimeUnit.NANOSECONDS.toMillis(search.workerNanos));
        search.result.complete(result);
    }

    private static void purgeExpiredTickets() {
        if (TICKETS.isEmpty()) {
            return;
        }
        long now = System.currentTimeMillis();
        ObjectIterator<Long2ObjectMap.Entry<Ticket>> iterator = TICKETS.long2ObjectEntrySet().iterator();
        while (iterator.hasNext()) {
            Ticket ticket = iterator.next().getValue();
            if (ticket.future.isDone() && now - ticket.completedAtMillis > TICKET_EXPIRY_MILLIS) {
                iterator.remove();
            }
        }
    }

    @SubscribeEvent
    public static void onServerStopping(ServerStoppingEvent event) {
        GENERATION.incrementAndGet();
        TICKETS.clear();
        CELL_CACHE.clear();
    }

    private static ThreadPoolExecutor createWorker() {
        ThreadPoolExecutor executor = new ThreadPoolExecutor(1, 1, 30L, TimeUnit.SECONDS, new LinkedBlockingQueue<>(), runnable -> {
            Thread thread = new Thread(runnable, "DivineRelics-StructureLocator");
            thread.setDaemon(true);
            thread.setPriority(Thread.MIN_PRIORITY);
            return thread;
        });
        executor.allowCoreThreadTimeOut(true);
        return executor;
    }

    /**
     * One search. Everything the worker touches is captured up front on the server thread; the worker never uses
     * {@link #level} or {@link #server}.
     */
    private static final class Search {
        final ServerLevel level;
        final MinecraftServer server;
        final int generation = GENERATION.get();
        final ResourceLocation structureId;
        final Structure structure;
        final List<RandomSpreadStructurePlacement> placements;
        final int[] nextRing;
        /** Unconfirmed candidates, nearest first. */
        final List<Candidate> pending = new ArrayList<>();
        final BlockPos origin;
        final int radius;
        final Long2ByteOpenHashMap cache;
        final CompletableFuture<Optional<BlockPos>> result = new CompletableFuture<>();

        final ChunkGenerator generator;
        final RandomState randomState;
        final long seed;
        final RegistryAccess registryAccess;
        final StructureTemplateManager templateManager;
        final LevelHeightAccessor heightAccessor;

        long workerNanos;
        int evaluatedCells;

        Search(ServerLevel level, ResourceLocation structureId, Structure structure, List<RandomSpreadStructurePlacement> placements,
               BlockPos origin, int radius, Long2ByteOpenHashMap cache) {
            this.level = level;
            this.server = level.getServer();
            this.structureId = structureId;
            this.structure = structure;
            this.placements = placements;
            this.nextRing = new int[placements.size()];
            this.origin = origin.immutable();
            this.radius = radius;
            this.cache = cache;
            this.generator = level.getChunkSource().getGenerator();
            this.randomState = level.getChunkSource().randomState();
            this.seed = level.getSeed();
            this.registryAccess = level.registryAccess();
            this.templateManager = level.getStructureManager();
            final int minBuildHeight = level.getMinBuildHeight();
            final int height = level.getHeight();
            this.heightAccessor = new LevelHeightAccessor() {
                @Override
                public int getHeight() {
                    return height;
                }

                @Override
                public int getMinBuildHeight() {
                    return minBuildHeight;
                }
            };
        }
    }
}
